// Writes the generated module lists from the module packages found in packages/modules/*:
//   packages/app/src/modules.generated.ts      the module definitions (createApp composes them)
//   packages/server/src/modules.generated.ts   the NestJS controllers (and providers) of every module that has a ./server part
//   packages/web/src/modules.generated.ts      the web manifests (every installed module that has a web/index.ts) and the endpoint owners
// FF_MODULES_OFF=a,b leaves those keys out. Deterministic: sorted by key, so the same folders always give the same files.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { discoverModules, installedModules, offKeys, root } from "./lib/modules.mjs";

const on = installedModules();
const off = offKeys();

function write(file, text) {
  mkdirSync(dirname(file), { recursive: true });
  if (!existsSync(file) || readFileSync(file, "utf8") !== text) writeFileSync(file, text);
}

write(join(root, "packages", "app", "src", "modules.generated.ts"), [
  "// GENERATED by scripts/gen-modules.mjs from packages/modules/*. Do not edit; it is rewritten on build, test and start.",
  'import type { ModuleDef } from "@fullfollow/core";',
  ...on.map((m, i) => `import mod${i} from ${JSON.stringify(m.name)};`),
  "",
  `export const modules: ModuleDef[] = [${on.map((_, i) => `mod${i}`).join(", ")}];`,
  `export const modulesOff: string[] = ${JSON.stringify(off)};`,
  "",
].join("\n"));

const withServer = on.filter((m) => m.server);
write(join(root, "packages", "server", "src", "modules.generated.ts"), [
  "// GENERATED by scripts/gen-modules.mjs from packages/modules/*. Do not edit; it is rewritten on build, test and start.",
  'import type { Provider, Type } from "@nestjs/common";',
  'import type { RouteDocs } from "@fullfollow/core";',
  ...withServer.map((m, i) => `import * as server${i} from ${JSON.stringify(`${m.name}/server`)};`),
  "",
  "/** The server part of an installed module: its NestJS controllers and the documentation of their routes (`GET /api/docs`) */",
  "export interface ModuleServer { key: string; controllers: Type<unknown>[]; docs: RouteDocs }",
  `export const moduleServers: ModuleServer[] = [${withServer.map((m, i) => `{ key: ${JSON.stringify(m.key)}, controllers: server${i}.controllers, docs: server${i}.docs }`).join(", ")}];`,
  "/** NestJS controllers of the installed modules; app.module spreads them */",
  "export const moduleControllers: Type<unknown>[] = moduleServers.flatMap((s) => s.controllers);",
  "/** NestJS providers of the installed modules (a module exports `providers` from its server part when it has any: services that start and stop with the server) */",
  `export const moduleProviders: Provider[] = [${withServer.map((_, i) => `...((server${i} as { providers?: Provider[] }).providers ?? [])`).join(", ")}];`,
  "",
].join("\n"));

// The web list: a static import of each installed module's web/index.ts (import.meta.glob cannot see FF_MODULES_OFF). The endpoint owners
// cover every module package found, switched off ones too (plain strings, no code), so the web never asks for an endpoint that is not there.
const webDir = join(root, "packages", "web", "src");
const withWeb = on.filter((m) => m.web);
const owners = discoverModules().flatMap((m) => m.endpoints.map((p) => [p, m.key]));
write(join(webDir, "modules.generated.ts"), [
  "// GENERATED by scripts/gen-modules.mjs from packages/modules/*. Do not edit; it is rewritten on build, test and start.",
  'import type { WebModule } from "./app/modules/types";',
  ...withWeb.map((m, i) => `import web${i} from ${JSON.stringify(relative(webDir, join(m.dir, "web", "index")).split(sep).join("/"))};`),
  "",
  "/** Manifests of the installed modules that have a web part (the shell builds routes, nav, cards, forms and settings from them) */",
  `export const webModules: WebModule[] = [${withWeb.map((_, i) => `web${i}`).join(", ")}];`,
  "/** API prefix to module key, for every module package found (also the switched off ones) */",
  `export const endpointOwners: [string, string][] = ${JSON.stringify(owners)};`,
  "",
].join("\n"));

// The module stylesheets: each installed module's web/styles.css is imported here, so it is compiled in the app's one Tailwind run (the theme
// variables it uses stay in the output, and so do the ones JS reads), and its web folder is scanned for utility classes.
const stylesDir = join(webDir, "styles");
const fromStyles = (p) => JSON.stringify(relative(stylesDir, p).split(sep).join("/"));
write(join(stylesDir, "modules.generated.css"), [
  "/* GENERATED by scripts/gen-modules.mjs from packages/modules/*. Do not edit; it is rewritten on build, test and start. */",
  // imports first: CSS wants every @import before any other rule
  ...withWeb.filter((m) => existsSync(join(m.dir, "web", "styles.css"))).map((m) => `@import ${fromStyles(join(m.dir, "web", "styles.css"))};`),
  ...withWeb.map((m) => `@source ${fromStyles(join(m.dir, "web"))};`),
  "",
].join("\n"));

console.log(`modules:${on.length ? on.map((m) => m.key).join(", ") : "none"}${off.length ? ` (off: ${off.join(", ")})` : ""}`);

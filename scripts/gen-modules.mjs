// Writes the generated module lists from the module packages found in packages/modules/*:
//   packages/app/src/modules.generated.ts      the module definitions (createApp composes them)
//   packages/server/src/modules.generated.ts   the NestJS controllers of every module that has a ./server part
// FF_MODULES_OFF=a,b leaves those keys out. Deterministic: sorted by key, so the same folders always give the same files.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { installedModules, offKeys, root } from "./lib/modules.mjs";

const on = installedModules();
const off = offKeys();

function write(file, text) {
  mkdirSync(dirname(file), { recursive: true });
  if (!existsSync(file) || readFileSync(file, "utf8") !== text) writeFileSync(file, text);
}

write(join(root, "packages", "app", "src", "modules.generated.ts"), [
  "// GENERATED by scripts/gen-modules.mjs from packages/modules/*. Do not edit; it is rewritten on build, test and start.",
  'import type { ModuleDef } from "@fullfollow/core";',
  ...on.map((m, i) => `import mod${i} from ${JSON.stringify(m.name)};`),
  "",
  `export const modules: ModuleDef[] = [${on.map((_, i) => `mod${i}`).join(", ")}];`,
  `export const modulesOff: string[] = ${JSON.stringify(off)};`,
  "",
].join("\n"));

const withServer = on.filter((m) => m.server);
write(join(root, "packages", "server", "src", "modules.generated.ts"), [
  "// GENERATED by scripts/gen-modules.mjs from packages/modules/*. Do not edit; it is rewritten on build, test and start.",
  'import type { Type } from "@nestjs/common";',
  ...withServer.map((m, i) => `import { controllers as controllers${i} } from ${JSON.stringify(`${m.name}/server`)};`),
  "",
  "/** NestJS controllers of the installed modules; app.module spreads them */",
  `export const moduleControllers: Type<unknown>[] = [${withServer.map((_, i) => `...controllers${i}`).join(", ")}];`,
  "",
].join("\n"));

console.log(`modules: ${on.length ? on.map((m) => m.key).join(", ") : "none"}${off.length ? ` (off: ${off.join(", ")})` : ""}`);

// Writes packages/app/src/modules.generated.ts from the module packages found in packages/modules/*.
// A module package declares itself with  "fullfollow": { "module": "<key>" }  in its package.json and
// default-exports its ModuleDef. FF_MODULES_OFF=a,b leaves those keys out of the generated list.
// Deterministic: sorted by key, so the same folders always give the same file.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const modulesDir = join(root, "packages", "modules");
const outFile = join(root, "packages", "app", "src", "modules.generated.ts");

const off = new Set((process.env.FF_MODULES_OFF ?? "").split(",").map((s) => s.trim()).filter(Boolean));

const found = [];
if (existsSync(modulesDir)) {
  for (const dir of readdirSync(modulesDir, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    const pkgPath = join(modulesDir, dir.name, "package.json");
    if (!existsSync(pkgPath)) continue;
    const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
    const key = pkg.fullfollow?.module;
    if (!key) continue;
    if (!/^[a-z][a-z0-9-]*$/.test(key)) throw new Error(`${pkgPath}: module key "${key}" must be lower-case letters, digits and dashes`);
    if (found.some((m) => m.key === key)) throw new Error(`${pkgPath}: duplicate module key "${key}"`);
    found.push({ key, name: pkg.name });
  }
}
found.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
const on = found.filter((m) => !off.has(m.key));
const offKeys = [...off].sort();

const lines = [
  "// GENERATED by scripts/gen-modules.mjs from packages/modules/*. Do not edit; it is rewritten on build, test and start.",
  'import type { ModuleDef } from "@fullfollow/core";',
  ...on.map((m, i) => `import mod${i} from ${JSON.stringify(m.name)};`),
  "",
  `export const modules: ModuleDef[] = [${on.map((_, i) => `mod${i}`).join(", ")}];`,
  `export const modulesOff: string[] = ${JSON.stringify(offKeys)};`,
  "",
];
const next = lines.join("\n");
mkdirSync(dirname(outFile), { recursive: true });
if (!existsSync(outFile) || readFileSync(outFile, "utf8") !== next) writeFileSync(outFile, next);
console.log(`modules: ${on.length ? on.map((m) => m.key).join(", ") : "none"}${offKeys.length ? ` (off: ${offKeys.join(", ")})` : ""}`);
